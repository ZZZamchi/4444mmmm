#!/usr/bin/env python3
"""Render the held-out evaluation as LaTeX for the paper.

Writes paper/heldout_results.tex: macros for every number the prose uses (\\HeldValidVtwoFA, ...)
and the table `tab:heldout`. Sources: data/real/v3/{test,valid}/scores.json (v2 / v2.1 / closed)
and, when present, the v4 scores (test: data/real/k22_score_test.json; valid: data/real/v4/valid/scores.json).
`paper_check.py` fails if the file differs from what this script renders, so no held-out number is typed by hand.

Usage: v3_tex.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCORES = {"Test": ROOT / "data" / "real" / "v3" / "test" / "scores.json",
          "Valid": ROOT / "data" / "real" / "v3" / "valid" / "scores.json"}
V4_SCORES = {"Test": ROOT / "data" / "real" / "k22_score_test.json",
             "Valid": ROOT / "data" / "real" / "v4" / "valid" / "scores.json"}
OUT = ROOT / "paper" / "heldout_results.tex"
ARMS = (("closed", "Closed", "closed $\\Ecl$"), ("v2", "Vtwo", "ours (v2)"), ("v2.1", "VtwoOne", "ours (v2.1)"))
LABELS = {"Test": "development (test)", "Valid": "held out (valid)"}


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\Held{name}}}{{{value}}}"


def num(n: int) -> str:
    return f"{n:,}"


def p_value(p: float) -> str:
    return "<10^{-3}" if p < 1e-3 else f"={p:.3f}" if p < 0.01 else f"={p:.2f}"


def from_verdicts(m: dict, n_pairs: int) -> dict:
    """Normalize a k22 score metrics block to the v3 fields the table uses."""
    v = m["verdicts"]
    rej_u, rej_f = v.get("U:reject", 0), v.get("F:reject", 0)
    decided = m["false_accept"] + m["accept"] + rej_u + rej_f
    return {**m, "reject_inequivalent": rej_u, "reject_equivalent": rej_f,
            "decided_pct": round(100 * decided / n_pairs, 2)}


def load_v4(split: str) -> dict | None:
    path = V4_SCORES[split]
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def arm_row(split: str, key: str, label: str, m: dict) -> str:
    lo, hi = m["false_accept_ci"]
    alo, ahi = m["accept_ci"]
    prefix = LABELS[split] if key == "closed" else ""
    return (f"{prefix} & {label} & {m['false_accept']} & "
            f"{m['false_accept_pct']:.1f} [{lo:.1f}--{hi:.1f}] & {m['accept']} & "
            f"{m['accept_pct']:.1f} [{alo:.1f}--{ahi:.1f}] & {m['reject_inequivalent']} / "
            f"{m['reject_equivalent']} & {m['decided_pct']:.1f}\\\\")


def arm_macros(split: str, name: str, m: dict) -> list[str]:
    lo, hi = m["false_accept_ci"]
    alo, ahi = m["accept_ci"]
    out = [macro(f"{split}{name}FA", m["false_accept"]), macro(f"{split}{name}FAPct", f"{m['false_accept_pct']:.1f}"),
           macro(f"{split}{name}FACI", f"{lo:.1f}--{hi:.1f}"),
           macro(f"{split}{name}Acc", m["accept"]), macro(f"{split}{name}AccPct", f"{m['accept_pct']:.1f}"),
           macro(f"{split}{name}AccCI", f"{alo:.1f}--{ahi:.1f}"),
           macro(f"{split}{name}RejU", m["reject_inequivalent"]), macro(f"{split}{name}RejF", m["reject_equivalent"]),
           macro(f"{split}{name}Decided", f"{m['decided_pct']:.1f}")]
    if "located_rejects" in m:
        out.append(macro(f"{split}{name}Located", m["located_rejects"]))
    return out


def render(scores: dict[str, dict], v4: dict[str, dict] | None = None) -> str:
    v4 = v4 or {}
    sources = "data/real/v3/*/scores.json"
    if v4:
        sources += " and v4 scores (k22_score_test.json, v4/valid/scores.json)"
    out = [f"% generated by scripts/real/v3_tex.py from {sources}; do not edit"]
    rows = []
    for split, s in scores.items():
        out += [macro(f"{split}Pairs", num(s["pairs"])), macro(f"{split}U", num(s["inequivalent"])),
                macro(f"{split}F", num(s["equivalent"]))]
        for key, name, label in ARMS:
            m = s["metrics"][key]
            out += arm_macros(split, name, m)
            rows.append(arm_row(split, key, label, m))
        if split in v4 and "v4" in v4[split]["metrics"]:
            m4 = from_verdicts(v4[split]["metrics"]["v4"], v4[split]["pairs"])
            out += arm_macros(split, "Vfour", m4)
            h5 = v4[split]["H5_v4_vs_v21_accepts"]
            b5, c5 = h5["discordant"]
            out += [macro(f"{split}HfiveB", b5), macro(f"{split}HfiveC", c5),
                    macro(f"{split}HfiveP", p_value(h5["p_one_sided"])),
                    macro(f"{split}HfiveFAIncrease", f"{h5['false_accept_increase_pp']:.2f}")]
            rows.append(arm_row(split, "v4", "ours (v4)", m4))
        rows.append("\\midrule" if split == "Test" else "")
        h = s["hypotheses"]
        b1, c1 = h["H1_closed_vs_v2_false_accepts"]["discordant"]
        b2, c2 = h["H2_v21_vs_v2_accepts"]["discordant"]
        out += [macro(f"{split}HoneB", b1), macro(f"{split}HoneC", c1),
                macro(f"{split}HoneP", p_value(h["H1_closed_vs_v2_false_accepts"]["p"])),
                macro(f"{split}HtwoB", b2), macro(f"{split}HtwoC", c2),
                macro(f"{split}HtwoP", p_value(h["H2_v21_vs_v2_accepts"]["p_one_sided"])),
                macro(f"{split}HtwoFAIncrease", f"{h['H2_v21_vs_v2_accepts']['false_accept_increase_pp']:.1f}")]
        if "H4_v2_valid_vs_test_outside_dev" in h:
            out.append(macro(f"{split}HfourP", p_value(h["H4_v2_valid_vs_test_outside_dev"]["p"])))
    rows = [r for r in rows if r]
    caption = (
        "Held-out evaluation with Claude Opus~5.5 at the budget of Table~\\ref{tab:full}. "
        "Development: the 1,140 test pairs on which the canonicalization rules, the two Lean-only additions "
        "of v2.1, and (later) the v4 normal-form and alignment rules were developed. Held out: the ProofNetVerif "
        "valid split, never read before each protocol was frozen and sharing no problem with the test split. "
        "v4 adds universe-0 when universes disagree, search alignment, one-sided residual locality, and "
        "content-free normal-form identity on residual and unknown pairs. FA: accepts of pairs labelled "
        "inequivalent; acc: accepts of pairs labelled equivalent (published labels); decided: accepts and "
        "rejects among all usable pairs. Closed rejects are refuted closed equivalences."
    )
    out += ["\\begin{table}[t]", "\\centering\\small\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{llrrrrrr}",
            "\\toprule",
            "split & check & FA & FA \\% [95\\% CI] & acc & acc \\% [95\\% CI] & rejects U / F & decided \\%\\\\",
            "\\midrule", *rows, "\\bottomrule", "\\end{tabular}",
            f"\\caption{{{caption}}}",
            "\\label{tab:heldout}", "\\end{table}", ""]
    return "\n".join(out)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    missing = [str(p) for p in SCORES.values() if not p.exists()]
    if missing:
        raise SystemExit(f"missing scores: {missing}")
    scores = {k: json.loads(p.read_text(encoding="utf-8")) for k, p in SCORES.items()}
    v4 = {k: s for k in SCORES if (s := load_v4(k)) is not None}
    OUT.write_text(render(scores, v4), encoding="utf-8")
    print("wrote", OUT, "with v4" if v4 else "without v4")


if __name__ == "__main__":
    main()
